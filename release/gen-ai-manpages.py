"""Generate man pages for the AI assistant commands.

Upstream repo regenerates its 29 man pages with help2man
(`release/update-manpages`).  help2man is not always available in the
internal build environment, so the new repoai commands ship hand-style
pages produced here instead -- mechanically, straight from each
command's real OptionParser and helpSummary, so they can never drift
from --help.  If you do have help2man, running
`release/update-manpages` will regenerate these too; that is fine, the
next run of this script matches it.

Usage: python3 release/gen-ai-manpages.py [--check]
"""

import argparse
import os
import sys
import time
from pathlib import Path

TOPDIR = Path(__file__).resolve().parent.parent
MANDIR = TOPDIR / "man"
sys.path.insert(0, str(TOPDIR))

import subcmds  # noqa: E402


def _bold(opt):
    return "\\fB%s\\fR" % opt.replace("-", "\\-")


def _option_tp(opt):
    """One option -> roff .TP block (help2man-ish style)."""
    names = []
    for short in opt._short_opts:
        names.append(_bold(short))
    for long in opt._long_opts:
        if opt.nargs:
            names.append(
                "%s=\\fI\\,%s\\/\\fR"
                % (_bold(long), opt.metavar or opt.dest.upper())
            )
        else:
            names.append(_bold(long))
    head = ", ".join(names)
    return ".TP\n%s\n%s\n" % (head, (opt.help or "").replace("-", "\\-"))


def render(cmd, month):
    """roff text for one command (mirrors the upstream page layout)."""
    name = cmd.NAME
    parser = cmd.OptionParser
    out = [
        '.\\" Generated by release/gen-ai-manpages.py (not hand-edited).',
        '.TH REPO "1" "%s" "repo %s" "Repo Manual"' % (month, name),
        ".SH NAME",
        "repo \\- repo %s - manual page for repo %s" % (name, name),
        ".SH SYNOPSIS",
        ".B repo",
        "\\fI\\,%s\\/\\fR [ARGS]" % name,
        ".SH DESCRIPTION",
        "Summary",
        ".PP",
        cmd.helpSummary.strip().replace("-", "\\-"),
        ".SH OPTIONS",
    ]
    main = [
        o for o in parser._get_all_options()
        if o not in sum((g.option_list for g in parser.option_groups), [])
    ]
    for opt in main:
        out.append(_option_tp(opt))
    for group in parser.option_groups:
        out.append(".SS %s" % group.title)
        for opt in group.option_list:
            out.append(_option_tp(opt))
    out.append(".PP")
    out.append("Run `repo help %s` to view the detailed manual." % name)
    return "\n".join(out) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="report pages that differ, write nothing")
    opts = ap.parse_args(argv)
    month = time.strftime("%B %Y")
    del subcmds.all_commands["branch"]  # alias, like upstream
    stale = []
    for name, cls in sorted(subcmds.all_commands.items()):
        if not getattr(cls, "IS_AI_COMMAND", False):
            continue
        text = render(cls(manifest=None, repodir=None), month)
        path = MANDIR / ("repo-%s.1" % name)
        if opts.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
            continue
        path.write_text(text, encoding="utf-8")
        print("generated %s" % path.relative_to(TOPDIR))
    if opts.check and stale:
        print("out of date: %s" % ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
